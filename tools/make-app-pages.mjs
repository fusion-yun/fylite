// Write the three prose pages of `app/`, once per language.
//
//     node tools/make-app-pages.mjs           # write app/*.html
//     node tools/make-app-pages.mjs --check   # fail if what is on disk differs
//
// ★WHY A BUILD STEP.  `index.html`, `features.html` and `credits.html` carry no
// part, no worker and no compute: their whole job was to have message keys
// filled in at run time.  For that they pulled the i18n runtime and eight
// catalogue files — 156 to 190 KB of JavaScript, of which 116 KB is tool prose
// they never show — and until it arrived their body was literally empty, which
// is also what a crawler saw.  Worse, the language lived only in localStorage,
// so the English site had no URL: it could not be linked to, the `<html lang>`
// and `<meta description>` in the source were Chinese for every reader, and the
// footer's QR resolved to whichever language the scanner happened to have
// stored.
//
// ★WHY GENERATED AND NOT HAND-WRITTEN TWICE.  The entrance's cards come from the
// one table the navigation is built from (`SCENARIOS` in `assets/site.js`), so
// the entrance cannot advertise a scenario that has moved.  Six hand-written
// files would put that table back into prose — twice, once per language — which
// is the thing `site.js` says in its own header it removed on purpose.  The
// catalogues stay the single source; the pages are the artefact, committed and
// checked, exactly like `assets/qr-*.svg`.
//
// ★DETERMINISM IS A REQUIREMENT, not a nicety: `--check` is a gate, so the same
// inputs must give the same bytes.  Nothing here reads the clock, the
// filesystem order, or a random source.

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import vm from 'node:vm';

const HERE = new URL('.', import.meta.url).pathname;
//: ★2026-09-02 工具搬回公开仓：`app/` 就在隔壁，相对路径重新成立。
const APP = HERE + '../app/';
const ASSETS = APP + 'assets/';
const TPL = HERE + 'app-pages/';
const PUB = 'https://fusion-yun.github.io/fylite/';

//: ★GENERATED by `rust/build.sh` — the one place the kernel's release, the
//: front end's and the ABI are written down.  Read rather than re-declared
//: so these static pages cannot disagree with the scenario pages' footer.
//: ★★2026-09-01 仓一分为二：这份 `abi.json` 由 fylite_kernel 的 `rust/build.sh`
//: 生成，并**装进本仓** `app/assets/`。此前这里读的是 `../rust/wasm/abi.json`
//: ——那是一条跨仓的运行期依赖，仓拆开之后本仓单独一份检出就再也生不出
//: 页脚上的版本号。读装进来的那份，本仓自足。
const VER = JSON.parse(readFileSync(
  HERE + '../app/assets/abi.json', 'utf8'));

// --- the catalogues, kept apart -------------------------------------------
//
// `FyI18n.t` falls back to zh for a key en does not have, so asking it for an
// English string cannot tell "translated" from "silently Chinese".  The
// register calls are intercepted instead and each language read from its own
// table — a missing key must be a visible failure here, not a quiet fallback.

globalThis.self = globalThis;
vm.runInThisContext(readFileSync(ASSETS + 'i18n.js', 'utf8'), { filename: 'i18n.js' });
const CAT = { zh: {}, en: {} };
globalThis.FyI18n.register = (code, table) => Object.assign(CAT[code], table);
for (const f of readdirSync(ASSETS).filter((f) => /^lang-.*\.js$/.test(f)).sort())
  vm.runInThisContext(readFileSync(ASSETS + f, 'utf8'), { filename: f });

// `site.js` guards every DOM touch on `typeof document !== 'undefined'`, so with
// no document it defines `FySite` and does nothing else.  The tables come from
// the file the browser uses; there is no second copy here.
vm.runInThisContext(readFileSync(ASSETS + 'site.js', 'utf8'), { filename: 'site.js' });
const { SCENARIOS, PAGES, TOOLS, ICONS } = globalThis.FySite;
//: ★the header strip and the entrance carry the scenarios AND the tool
//: pages (2026-09-01) — see the note on `TOOLS` in `site.js`.  One list
//: here so the generated pages cannot disagree with the injected nav.
const DESTINATIONS = [...SCENARIOS, ...TOOLS];

const LANGS = ['zh', 'en'];
const HTMLLANG = { zh: 'zh-CN', en: 'en' };
const LABEL = { zh: '中文', en: 'English' };

/** The file a page is written to in a given language. */
const file = (id, lang) => (lang === 'zh' ? `${id}.html` : `${id}.${lang}.html`);
/** The published address, named once; the QR payload is generated from the
    same string by `tools/make-app-qr.py --url`. */
const SITE_URL = 'https://fusion-yun.github.io/fylite';

const esc = (s) => String(s).replace(/[&<>"]/g,
  (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const plain = (s) => esc(String(s).replace(/<[^>]*>/g, ''));

function t(lang, key, params) {
  const v = CAT[lang][key];
  if (v === undefined) throw new Error(`message key \`${key}\` is missing from ${lang}`);
  if (!params) return v;
  return v.replace(/\{(\w+)\}/g, (m, n) => (n in params ? params[n] : m));
}

// --- the pieces a page does not spell out itself ---------------------------

//: ★★THE STRIP IS ICONS (2026-09-01, 用户裁定) and these pages carry no i18n
//: runtime — `validate-site.mjs` fails any generated page that still has a
//: `data-i18n` — so the name that the dynamic pages attach with
//: `data-i18n-title` / `-aria` is written out LITERALLY here, in this page's
//: language.  Same string, same two attributes, two ways of arriving at it.
function nav(lang) {
  return DESTINATIONS.map((S) => {
    const name = esc(plain(t(lang, S.nav)));
    //: ★`href` FIRST, before `class`: `validate-site.mjs` pulls the strip's
    //: links out with `/<a href="([^"]+)"/` and would silently match nothing
    //: if another attribute came first — the same shape of blind spot as the
    //: `data-part="([a-z]+)"` one that hid 50 panels.
    return `    <a href="${S.href}" class="navic" title="${name}"`
         + ` aria-label="${name}">${ICONS[S.id]}</a>`;
  }).join('\n');
}

function cards(lang) { return grid(lang, DESTINATIONS); }

function grid(lang, table) {
  //: ★on a CARD the icon joins the words instead of replacing them (用户裁定):
  //: the strip is scanned, a card is read.
  const c = table.map((S) =>
    `  <a class="card panel" href="${S.href}">\n`
    + `    <h3><span class="card-ic">${ICONS[S.id]}</span>`
    + `<span>${t(lang, S.card + '.h')}</span></h3>\n`
    + `    <p>${t(lang, S.card + '.p')}</p>\n`
    + `  </a>`).join('\n');
  return `<div class="cards">\n${c}\n</div>`;
}

//: ★ONE GRID OF FOUR (2026-09-01, 用户裁定).  It was briefly two — three
//: scenarios, then the tool page under a heading of its own — because the
//: heading above counted 「三个场景」 and a fourth card under it would have made
//: the entrance contradict itself on one screen.  The ruling is four pages, so
//: the SENTENCES moved instead of the card: the section is 「四个页面」 now and
//: says which of them computes and which does not.  ★The two TABLES stay
//: separate all the same — `SCENARIOS` and `TOOLS` answer 「what kind of page
//: is this」, which is still two answers (`site.js` argues it at length); this
//: grid answers 「where can I go」, which is one.

// ★★The warning band.  It is expanded HERE rather than left as a `data-i18n`
// hook because a generated page runs no i18n — `validate-site.mjs` fails any
// of them that still carries one — so the sentences have to be in the markup,
// in that page's language.  The five dynamic pages carry the same two notices
// with `data-i18n`; one key, two ways of arriving at it, which is the standing
// arrangement for every string on these six pages.
//
// ★★TWO SPANS, TWO SCOPES (2026-09-05, 用户裁定).  `chrome.alpha` says what
// state this build is in and is true of every flavour; `chrome.internal_only`
// says who may hold this copy and is true of the internal one only.  They are
// two ELEMENTS rather than one longer sentence because the public build has to
// be able to drop the second and keep the first, and dropping an element is a
// thing a publisher can do exactly (`tools/app-flavour.mjs`); dropping half a
// sentence is a thing it can only approximate.
function warnBand(lang) {
  return '  <p class="warn-band" role="note">'
       + `<span class="warn-alpha">${t(lang, 'chrome.alpha')}</span>`
       + `<span class="warn-io">${t(lang, 'chrome.internal_only')}</span></p>`;
}

function alternates(id) {
  //: both directions and a self-reference: a crawler that finds either file
  //: learns the whole set, which is the only way the two are known to be the
  //: same page in two languages rather than two pages
  return LANGS.map((l) =>
    `<link rel="alternate" hreflang="${l}" href="${PUB}${file(id, l)}">`).join('\n');
}

function foot(id, lang) {
  const other = LANGS.find((l) => l !== lang);
  //: ★`external` 的条目不是这套生成器出的文件（用户指南是 MyST 编译进
  //: `app/guide/` 的静态书），所以它给的是自己的 `href`，而不是由 `file()`
  //: 推出的按语言分文件名；`langs` 限定它出现在哪些语言的页面上——一个只有
  //: 中文版的目的地不该出现在英文页的页脚里。
  const links = PAGES
    .filter((P) => P.id !== id && (!P.langs || P.langs.includes(lang)))
    .map((P) => `  <a href="${P.external ? P.href : file(P.id, lang)}">`
                + `${t(lang, P.nav)}</a>`).join('\n');
  return [
    '<footer>',
    `  <a class="mark" href="${file('index', lang)}" tabindex="-1" aria-hidden="true"`
      + '><img src="assets/fy_mark.svg" alt="" width="24" height="24"></a>',
    links,
    //: ★on a static page the language switch is a LINK, not a button: there is
    //: nothing to re-render, there is another file.  The flag it shows is the
    //: language you are READING — the control's state — so what pressing it
    //: does is said in words, as an action, in the language of this page.
    //: `hreflang` still describes the FILE at the other end, which is what that
    //: attribute is for and the only machine-readable half of the pair.
    `  <a class="iconbtn" href="${file(id, other)}" hreflang="${other}"`
      + ` title="${plain(t(lang, 'lang.switch', { to: LABEL[other] }))}"`
      + ` aria-label="${plain(t(lang, 'lang.switch', { to: LABEL[other] }))}"`
      + `><img class="flag" src="assets/flag-${lang}.svg" alt="" width="24" height="16"></a>`,
    `  <span class="copy">${t(lang, 'foot.copyright')}</span>`,
    //: ★the same version chip the scenario pages get from `site.js`, baked in
    //: here because these pages load no JavaScript at all.  One spec, two
    //: emitters — `validate-site.mjs` judges both against the same rule.  The
    //: numbers come from `rust/wasm/abi.json`, GENERATED by `rust/build.sh`,
    //: so regenerating these pages after a kernel build carries the new
    //: version across and a stale page is a visible diff rather than a lie.
    `  <span class="ver" title="kernel ${VER.kernel_version}`
      + ` · interface ${VER.abi_version} · app ${VER.app_version}">`
      + `${plain(t(lang, 'foot.version', { kernel: VER.kernel_version,
                                           abi: VER.abi_version,
                                           app: VER.app_version }))}</span>`,
    //: generated once by `tools/make-app-qr.py`: a printed code cannot ask
    //: where it is being served from, so the payload is the published url.
    //: ★ONE code for the whole site, not one per page (2026-09-01 ruling), and
    //: ★hidden on the desktop viewer by `assets/host.js` + one CSS rule — the
    //: markup is identical on both hosts because the bytes are.
    `  <a class="qr" href="${SITE_URL}" title="${SITE_URL}"`
      + `><img src="assets/qr-site.svg" alt="QR" width="37" height="37"></a>`,
    '</footer>',
  ].join('\n');
}

// ★The page stamps its own language.  Without this a reader who opens the
// Chinese entrance in an English-locale browser and clicks through to a
// scenario gets an English tool page: the scenario pages resolve their language
// from localStorage, then from `navigator.languages`.  The rule this encodes is
// the same one the URLs encode — the language you are reading IS your language —
// and it is what makes "no automatic redirect at the entrance" coherent rather
// than merely stubborn.
const stamp = (lang) =>
  `<script>try{localStorage.setItem('fylite-lang','${lang}')}catch(e){}</script>`;

// --- expansion -------------------------------------------------------------

//: 模块级，因为**两处都要用它**：渲染时填进链接，`checkRepoLinks()` 时落到磁盘上。
const ACKFILE = 'docs/ACKNOWLEDGEMENTS.md';

function build(id, lang) {
  const src = readFileSync(TPL + id + '.html', 'utf8');
  const slots = {
    '@htmllang': HTMLLANG[lang],
    '@alternates': alternates(id) + '\n' + stamp(lang),
    '@nav': nav(lang),
    '@warn': warnBand(lang),
    '@cards': cards(lang),
    '@footer': foot(id, lang),
    '@home': file('index', lang),
    //: ★★`blob/main` WAS A DEAD LINK ON EVERY ONE OF THESE PAGES, in both
    //: languages: this repository has no `main`.  `git ls-remote --heads`
    //: gives eleven branches, the line is `develop`, and the seven「原文在这里」
    //: links on the credits and features pages all pointed at a ref that has
    //: never existed.  ★They fail the way that survives longest — GitHub
    //: answers 404 with a page, so nothing in a build or a link-checker of
    //: ours ever saw a broken response; only a reader clicking did.
    //: ★The branch is a slot rather than seven literals so that the next time
    //: the line moves, it moves once.
    '@repo': 'https://github.com/fusion-yun/fylite/blob/develop',
    //: ★★IT MOVED, AND THERE IS ONLY ONE (2026-09-08).  `7e3969f` folded the
    //: acknowledgements into the documentation book as `docs/ACKNOWLEDGEMENTS.md`
    //: and the split-off `ACKNOWLEDGEMENTS.en.md` did not survive the move — so
    //: the language-dependent slot this used to be pointed the ENGLISH credits
    //: page at a file that exists in no branch.  One file, both languages, and
    //: the check below now refuses any `{{@repo}}` path that is not on disk.
    '@ackfile': ACKFILE,
  };
  return src.replace(/\{\{([^}]+)\}\}/g, (m, spec) => {
    if (slots[spec] !== undefined) return slots[spec];
    if (spec.startsWith('@page:')) return file(spec.slice(6), lang);
    const [key, mode] = spec.split('|');
    if (key.startsWith('@')) throw new Error(`unknown slot \`${spec}\` in ${id}.html`);
    return mode === 'text' ? plain(t(lang, key)) : t(lang, key);
  });
}

//: ★★**每一条指向仓库的链接，仓库里都得真有那个文件**（2026-09-08）。
//: 这一类缺陷这里犯过两次：先是分支名从来不存在，后是 `NOTICE` / `FEATURE.md` /
//: `ACKNOWLEDGEMENTS.en.md` 三份被移出公开仓、而链接留在页上。两次都活得很久，
//: 因为**它们不是坏响应**：GitHub 用一张 200 的页面回答 404，构建、闸子、连
//: 链接检查器都看不出来，只有点下去的读者看得出来。
//: ★所以判据落在**磁盘上**而不是网络上：模板里每一个 `{{@repo}}/…` 的路径，
//: 按仓根解析必须存在。离线、无网络、和渲染同一次跑完。
//: ★只管本仓的路径。外部链接（上级项目、上游代码）这里判不了——它们要么由人核，
//: 要么由一道会联网的闸子核，那是另一件事。
function checkRepoLinks() {
  const REPO = HERE + '../';
  let n = 0, dead = [];
  for (const id of ['index', 'features', 'credits']) {
    const src = readFileSync(TPL + id + '.html', 'utf8');
    for (const m of src.matchAll(/\{\{@repo\}\}\/([^"'\s<>]+)/g)) {
      //: 路径本身可能还含一个槽位（`{{@ackfile}}`），先展开再落到磁盘上
      const rel = m[1].replace(/\{\{@ackfile\}\}/g, ACKFILE);
      if (/\{\{/.test(rel)) {
        //: 路径里还有别的槽位——这道闸子只认得 `@ackfile` 那一个。与其悄悄跳过，
        //: 不如判红：一条查不了的链接和一条断了的链接，后果是一样的。
        dead.push(`${id}.html -> ${rel}（含本闸不认识的槽位）`);
        continue;
      }
      n++;
      try { readFileSync(REPO + rel); } catch (e) { dead.push(`${id}.html -> ${rel}`); }
    }
  }
  if (dead.length) {
    console.log('  FAIL 指向仓库的链接，文件不在仓里：');
    for (const d of dead) console.log('       ' + d);
    console.log('       ★这类链接不会返回坏响应——GitHub 用一张页面回答 404。');
    return dead.length;
  }
  console.log(`  ok   ${n} 条指向仓库的链接，逐条在仓里找到了文件`);
  return 0;
}

const check = process.argv.includes('--check');
let bad = 0;
bad += checkRepoLinks();
//: ★★**先判后写**。这道闸子原来跑在写入之后：一条断链照样被写进页面，然后才退非零
//: ——而下一趟 `--check` 会说「页面与生成器一致」，因为两边一样地错。判据要能拦住
//: 的是**写入**，不是事后报告。
if (!check && bad) { console.log('\n一页也没写。'); process.exit(1); }
for (const id of ['index', 'features', 'credits'])
  for (const lang of LANGS) {
    const out = build(id, lang);
    const path = APP + file(id, lang);
    if (check) {
      let have = null;
      try { have = readFileSync(path, 'utf8'); } catch (e) { /* missing */ }
      if (have !== out) {
        console.log(`  FAIL ${file(id, lang)} differs from a fresh render`
                    + (have === null ? ' (missing)' : ''));
        bad++;
      } else console.log(`  ok   ${file(id, lang)}`);
    } else {
      writeFileSync(path, out);
      console.log(`  wrote ${file(id, lang)}  ${out.length} chars`);
    }
  }
if (check) {
  console.log(bad ? `\nFAILED (${bad}) — run \`node tools/make-app-pages.mjs\`` : '\nPASS');
  process.exit(bad ? 1 : 0);
}
//: ★写入那一趟也要判红：链接断了不是「下次 --check 再说」的事——重跑生成器**正是**
//: 那条断链会被写进页面的时刻。
if (bad) process.exit(1);
