"""`machine_desc/` holds device descriptions the package can actually read.

★★**Why this exists.**  Until 2026-08-22 this repository could describe one
machine on the Python side (EAST) and a second one only as a browser asset
(`app/assets/dev-iter.js`), in a shape nothing in `fylite` reads.  So "which
machines does fylite know?" had two answers in two formats, and the answer a
Python caller could use was one.

The six machines converged out of fydata are documents now, generated by
`tools/fydata-to-fyo-device.py`.  A generated file that nobody loads is
decoration, and a generated file nobody re-derives drifts from its source —
so this gate does both: every document goes through the real reader
(`device.load_device`, contract check included), and where fydata is on hand
the generator is re-run and its output diffed against what is committed.

★No physics is asserted here and none belongs: this is about whether a
description can be READ and whether it still matches the tree it came from.
The one numerical case is a cross-check between two descriptions of the SAME
machine that must not disagree — the ITER document and the browser asset,
both derived from the same fydata files.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path

import pytest

from fylite import device

ROOT = Path(__file__).resolve().parents[2]
DESC = ROOT / "machine_desc"
FYDATA_ENV = "FYDATA_DIR"

#: EAST is hand-maintained; every other document is generated.
HANDWRITTEN = {"east"}

DOCS = sorted(DESC.glob("*/*_device.yaml"))

pytestmark = pytest.mark.skipif(not DOCS, reason="no machine_desc/ in this tree")


def _ids(p: Path) -> str:
    return p.parent.name


@pytest.mark.parametrize("doc", DOCS, ids=_ids)
def test_every_description_loads_through_the_real_reader(doc: Path):
    """★`load_device`, not `yaml.safe_load`: the contract is the point.

    It refuses a document with no semantic header and one that is missing an
    IDS group, which is exactly what a half-converted machine looks like.
    """
    dev = device.load_device(doc)
    assert dev["@type"] == "fyo:DeviceDescription"
    assert dev["@id"].endswith(f"device/{_ids(doc)}") or _ids(doc) == "east"
    for group in device.DEVICE_REQUIRED:
        assert group in dev, group


@pytest.mark.parametrize("doc", [d for d in DOCS if _ids(d) not in HANDWRITTEN],
                         ids=_ids)
def test_a_group_with_no_upstream_data_says_so(doc: Path):
    """★★An IDS group that carries nothing must SAY it carries nothing.

    The required-group check exists because a document quietly missing
    `pf_active` yields a machine with no coils rather than an error.  Writing
    an empty group to satisfy that check would put the silence back — so an
    empty group here has to carry `fylite:absent` with a reason, and a
    non-empty one must not claim to be absent.
    """
    dev = device.load_device(doc)
    bad = []
    for group in ("magnetics", "pf_active", "wall", "interferometer",
                  "polarimeter", "data_source", "operational", "solver_dims"):
        node = dev[group]
        absent = isinstance(node, dict) and "fylite:absent" in node
        content = _has_content(group, node)
        if content and absent:
            bad.append(f"{group}: marked absent but carries data")
        if not content and not absent:
            bad.append(f"{group}: empty and says nothing about why")
    assert not bad, f"{doc.relative_to(ROOT)}:\n  " + "\n  ".join(bad)


def _has_content(group: str, node) -> bool:
    if not isinstance(node, dict):
        return bool(node)
    #: ★the DD's ARRAYS, which is the canonical spelling (`@fyo-table
    #: DEVICE`).  These read `{count, channel}` and a mapping `description_2d`
    #: for one batch — the two dialects this table exists to collapse.
    if group == "magnetics":
        return any(node.get(k) for k in ("flux_loop", "b_field_pol_probe"))
    if group == "pf_active":
        return bool(node.get("coil"))
    if group == "wall":
        d2 = node.get("description_2d") or [{}]
        return bool(d2[0].get("limiter", {}).get("unit"))
    if group in ("interferometer", "polarimeter"):
        return bool(node.get("channel"))
    #: `data_source` / `operational` / `solver_dims` carry no array — any key
    #: that is not the header or the absence marker is content.
    return any(not k.startswith(("@", "fylite:absent")) for k in node)


@pytest.mark.parametrize("doc", [d for d in DOCS if _ids(d) not in HANDWRITTEN],
                         ids=_ids)
def test_every_generated_group_names_the_file_it_came_from(doc: Path):
    """A converted group carries `fylite:source`, and it resolves in fydata.

    ★The path is checked as a STRING even when fydata is absent: a
    provenance line that names nothing is the failure mode a converter has,
    and it does not need the source tree present to be caught.
    """
    dev = device.load_device(doc)
    named = [dev[g].get("fylite:source") for g in ("magnetics", "pf_active", "wall")
             if _has_content(g, dev[g])]
    assert named, f"{doc.relative_to(ROOT)} converted nothing at all"
    #: ★both spellings, deliberately.  fydata renamed its top directory
    #: `machine/` -> `device/` on 2026-09-02; the committed documents were
    #: derived before that and say `machine/`, a fresh run says `device/`.
    #: Pinning either one alone would turn「这批文档比改名早」into a red gate,
    #: which is not what this assertion is for — it is here to catch a
    #: provenance line that names NOTHING.
    #: ★★2026-09-02 再加一种：权威源改成 **fydoc**（用户裁定），它的布局是
    #: `device/<id>/abox/…`，不是 fydata 的 `…/tokamak/<id>/…`。三种都认，
    #: 判的仍是同一件事——这一行有没有指向某个具体文件。
    for src in named:
        assert src and re.match(
            r"(?:(?:machine|device)/tokamak/\w+/|device/\w+/abox/)", str(src)), src


def _fydata() -> Path:
    root = os.environ.get(FYDATA_ENV)
    if not root:
        pytest.skip(f"set ${FYDATA_ENV} to a fydata checkout to re-derive "
                    "the generated device descriptions")
    p = Path(root).expanduser()
    if not (p / "device" / "tokamak").is_dir():
        pytest.skip(f"${FYDATA_ENV}={p} does not look like a fydata checkout")
    return p


def test_the_generated_descriptions_still_match_their_source(tmp_path):
    """★★Re-run the generator and diff — the only thing that keeps a
    generated file honest.

    A converted document is a claim about somebody else's tree.  Committing
    it and never re-deriving it means the day upstream changes a coil, this
    repository keeps describing the old machine with a provenance block that
    says otherwise — which is worse than having no description, because it
    reads as sourced.

    ★What this gate must NOT do is confuse「上游改了」with「这份检出里没有那台
    机器」.  fydata checkouts differ, and only the machines whose manifest is
    present in THIS one can be re-derived; the rest are reported as not
    checked and left alone.  Calling them drift would tell the reader to
    re-run and commit, and that would delete their documents.
    """
    fydata = _fydata()
    gen = ROOT / "tools" / "fydata-to-fyo-device.py"
    r = subprocess.run([sys.executable, str(gen), "--all",
                        "--fydata", str(fydata), "-o", str(tmp_path)],
                       capture_output=True, text=True)
    assert r.returncode == 0, r.stderr
    #: ★★WHICH MACHINES THIS CHECKOUT CAN SPEAK FOR.  A machine is derivable
    #: only if the tree carries its manifest; a checkout that does not have
    #: one cannot say anything about the committed document, and「生成器不再
    #: 产出它」would be a false accusation.  ★Measured 2026-08-26: a fydata
    #: checkout at c61b408 carries a manifest for EAST alone, so this gate
    #: reported six machines as drifted and told the reader to re-run and
    #: commit — which would have DELETED six device descriptions.  A gate
    #: whose remedy destroys data on a partial checkout is worse than no gate.
    have = {q.parent.name
            for q in (fydata / "device" / "tokamak").glob("*/machine.yaml")}
    drift, absent = [], []
    for doc in DOCS:
        ids = _ids(doc)
        if ids in HANDWRITTEN:
            continue
        if ids not in have:
            absent.append(ids)
            continue
        fresh = tmp_path / ids / doc.name
        if not fresh.is_file():
            drift.append(f"{ids}: its manifest is in this checkout and the "
                         "generator still emitted nothing")
        elif fresh.read_text(encoding="utf-8") != doc.read_text(encoding="utf-8"):
            drift.append(f"{ids}: committed file differs from a fresh run")
    if absent:
        #: said out loud, never silently: a reader has to know the gate
        #: checked less than the whole set, and exactly how much less
        print(f"\n  not derivable from ${FYDATA_ENV}={fydata} (no manifest "
              f"in that checkout, so not checked): {sorted(absent)}")
    #: ★and the gate must still have checked SOMETHING — a checkout carrying
    #: no manifest at all would otherwise pass by having nothing to compare
    assert have, (
        f"${FYDATA_ENV}={fydata} carries no machine manifest at all; this "
        "gate would pass by having nothing to check")
    assert not drift, (
        "re-run `python3 tools/fydata-to-fyo-device.py --all` and commit:\n  "
        + "\n  ".join(drift))


def test_the_generator_refuses_to_overwrite_the_hand_written_east_document(tmp_path):
    """★EAST's document is strictly richer than fydata's EAST tree — the est2
    79-probe basis, the fit-control block, the passive set and the supply
    parameters have no upstream at all.  A generator that would answer for it
    is a generator that can delete all of that in one run."""
    fydata = _fydata()
    r = subprocess.run([sys.executable, str(ROOT / "tools" / "fydata-to-fyo-device.py"),
                        "east", "--fydata", str(fydata), "-o", str(tmp_path)],
                       capture_output=True, text=True)
    assert r.returncode != 0, "it produced an EAST document"
    assert "refusing to overwrite" in r.stderr
    assert not list(tmp_path.glob("**/*.yaml"))


#: ★★2026-09-02：`fylite_device_<id>.json` 是**手工件**——全仓没有任何工具产出
#: 它，而内核仓的 `machine_desc/` 已废弃，拖回工具只出 `<id>_device.yaml`。所以
#: 这一族在今天的检出上通常是空的，下面几条随之 skip 并点名缺的是什么，与本仓
#: 其它「需要机器数据」的判据同一套政策。★它们不是被删掉：这几份文档一旦有了
#: 正式的家（多半是 fydata），把它拖回来这几条就自己回来。
APP_DOCS = sorted(DESC.glob("*/fylite_device_*.json"))


def test_every_generated_browser_document_still_matches_its_source(tmp_path):
    """★The browser document is a COPY of the fyo one, so it can go stale.

    `tools/fyo-device-to-app.py` reads the fyo description through the
    declared field table and writes the page's import document.  A copy that
    is committed and never re-derived is the same hazard the fydata
    conversion has one level up — and this repository has just paid for it
    once, in EAST's wall.
    """
    gen = ROOT / "tools" / "fyo-device-to-app.py"
    made = [p for p in APP_DOCS if _ids(p) not in HANDWRITTEN]
    if not made:
        pytest.skip("no generated browser document in this tree")
    r = subprocess.run([sys.executable, str(gen), "--all", "-o", str(tmp_path)],
                       capture_output=True, text=True, cwd=str(ROOT))
    #: ★a non-zero exit is EXPECTED here: three machines are refused for
    #: want of a limiter, coils or a vacuum field.  What matters is that the
    #: ones it does emit match.
    drift = []
    for doc in made:
        fresh = tmp_path / _ids(doc) / doc.name
        if not fresh.is_file():
            drift.append(f"{_ids(doc)}: the generator no longer emits it "
                         f"({r.stderr.strip().splitlines()[-1] if r.stderr else ''})")
        elif fresh.read_text(encoding="utf-8") != doc.read_text(encoding="utf-8"):
            drift.append(f"{_ids(doc)}: committed file differs from a fresh run")
    assert not drift, (
        "re-run `python3 tools/fyo-device-to-app.py --all` and commit:\n  "
        + "\n  ".join(drift))


@pytest.mark.parametrize("doc", APP_DOCS, ids=_ids)
def test_a_browser_document_says_which_machine_it_is(doc: Path):
    """★`fylite:device_id` is what the page resolves `?device=<id>` against;
    without it an imported machine arrives called "imported"."""
    d = json.loads(doc.read_text(encoding="utf-8"))
    assert d["@type"] == "fylite:DeviceDescription/1"
    assert d["fylite:device_id"] == _ids(doc)


