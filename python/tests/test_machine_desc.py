ITER_DOC = DESC / "iter" / "iter_device.yaml"
PRESETS = ROOT / "app" / "devices"
CATALOGUE = PRESETS / "catalogue.jsonld"


@pytest.mark.skipif(not CATALOGUE.is_file(), reason="this tree ships no presets")
@pytest.mark.skipif(
    not APP_DOCS,
    reason="没有 machine_desc/<id>/fylite_device_<id>.json —— 那是**手工件**，"
           "全仓没有任何工具产出它；内核仓的 machine_desc/ 2026-09-02 废弃后，"
           "拖回工具只出 <id>_device.yaml。这几份文档有了正式的家之后这条自己回来")
def test_every_preset_is_the_import_document_it_claims_to_be():
    """★★A preset is the machine's import document, published — a byte-for-byte
    copy of `machine_desc/<id>/fylite_device_<id>.json`.

    A copy, so it can go stale, so it is diffed here.  ★And a COPY rather
    than a regeneration because one of them is not generated at all: EAST's
    import document is hand-completed (`tools/make-east-inputs.py` writes the
    79 probes into it).  Comparing against the import document makes "the
    preset is that machine" one check for every machine instead of two rules;
    where the import document itself comes from is checked next door.
    """
    cat = json.loads(CATALOGUE.read_text(encoding="utf-8"))
    entries = cat.get("fylite:devices") or []
    assert entries, "the catalogue lists no preset"
    drift = []
    for e in entries:
        dev_id, name = e["fylite:device_id"], e["fylite:document"]
        shipped = PRESETS / name
        source = DESC / dev_id / f"fylite_device_{dev_id}.json"
        if not shipped.is_file():
            drift.append(f"{name}: listed in the catalogue and absent")
        elif not source.is_file():
            drift.append(f"{dev_id}: no import document to be a copy of")
        elif shipped.read_text(encoding="utf-8") != source.read_text(encoding="utf-8"):
            drift.append(f"{name}: differs from {source.relative_to(ROOT)}")
    assert not drift, (
        "re-run `python3 tools/fyo-device-to-app.py --all --preset "
        "-o app/devices` and commit:\n  " + "\n  ".join(drift))


@pytest.mark.skipif(not CATALOGUE.is_file(), reason="this tree ships no presets")
def test_every_preset_says_where_its_numbers_came_from():
    """★★`app/` is published, so a preset is a REDISTRIBUTION — and the one
    thing a redistribution must not do is arrive anonymous.

    ★This checks that provenance is DECLARED, not that it is a publication.
    Whether a given machine may be published is a decision this repository
    records rather than makes: `east` is an operator's own description with a
    real discharge in it and is a preset by explicit decision (2026-08-22);
    `cfetr` and `best` rested on private communications and were withdrawn on
    2026-09-01, which the catalogue records under `fylite:not_presets` beside
    every other machine it does not ship.  What a gate can hold is that each
    published machine says where its numbers came from — a reader who finds a
    coil geometry on the public site can trace it to a named source, and a
    machine added later cannot slip in without one.
    """
    cat = json.loads(CATALOGUE.read_text(encoding="utf-8"))
    bad = []
    for e in cat.get("fylite:devices") or []:
        src = e.get("prov:wasDerivedFrom")
        if not src or not all(isinstance(x, str) and len(x) > 20 for x in src):
            bad.append(f"{e.get('fylite:device_id')}: no prov:wasDerivedFrom")
        #: a machine carrying somebody's measured shot must SAY it does
        if e.get("fylite:reference_discharge") \
                and not e.get("fylite:reference_discharge_note"):
            bad.append(f"{e.get('fylite:device_id')}: ships a reference "
                       f"discharge and does not say so")
    assert not bad, "preset provenance:\n  " + "\n  ".join(bad)


@pytest.mark.skipif(not CATALOGUE.is_file(), reason="this tree ships no presets")
def test_the_catalogue_and_the_directory_agree():
    """★A document in `app/devices/` that the catalogue does not list is a
    machine being published with nothing recording where it came from —
    which is the failure mode the catalogue exists to prevent, arriving by
    the back door."""
    cat = json.loads(CATALOGUE.read_text(encoding="utf-8"))
    listed = {e["fylite:document"] for e in cat.get("fylite:devices") or []}
    present = {p.name for p in PRESETS.glob("*.jsonld")} - {"catalogue.jsonld"}
    assert present == listed, {"in the directory only": sorted(present - listed),
                               "in the catalogue only": sorted(listed - present)}


@pytest.mark.skipif(not (ITER_DOC.is_file() and (PRESETS / "iter.jsonld").is_file()),
                    reason="no ITER description on both sides")
def test_the_iter_document_and_the_browser_preset_are_the_same_machine():
    """★★Two files describe ITER — this document and the browser's
    `dev-iter.js` — and both are generated from the same fydata files by
    different tools.  Two derivations of one machine that nothing compares
    will diverge on the first change to either generator, and the page and
    the Python side would then disagree about where a coil is with no test
    able to say so.

    ★Coils and R0/B0 only.  The two are not the same DOCUMENT — the preset
    carries a grid RESOLUTION and a device id, which are the page's and not
    the machine's, and the fyo document carries provenance and the absence
    markers the page has no use for.  What must agree is the machine.
    """
    dev = device.load_device(ITER_DOC)
    pre = json.loads((PRESETS / "iter.jsonld").read_text(encoding="utf-8"))

    want = {}
    for c in pre["pf_active"]["coil"]:
        el = c["element"][0]
        rect = el["geometry"]["rectangle"]
        want[c["name"]] = (rect["r"], rect["z"], rect["width"], rect["height"],
                           float(el["turns_with_sign"]))
    assert len(want) == 12, f"the preset carries {len(want)} coils"

    got = {}
    for coil in dev["pf_active"]["coil"]:
        el = coil["element"][0]
        rect = el["geometry"]["rectangle"]
        #: ★`turns_with_sign` on the ELEMENT — the DD's own spelling, and the
        #: canonical one.  It was `coil.turns` for one batch.
        got[coil["name"]] = (rect["r"], rect["z"], rect["width"],
                             rect["height"], float(el["turns_with_sign"]))
    assert set(got) == set(want), (sorted(got), sorted(want))
    for name in want:
        assert got[name] == pytest.approx(want[name], rel=0, abs=0), name

    assert dev["machine"]["r_centre"] == pytest.approx(pre["tf"]["r0"])
    #: ★★2026-09-02 的一个**已知缺口，留在明处**：装置牌改为从 fydoc 的 A-Box
    #: 按需拖回之后，拖回来的 ITER 卡片**没有 `machine.fylite:b0`**（内核仓那份
    #: committed 的有，5.3 T）。上游的 `tf` 组带着 `b_field_phi_vacuum_r`，但那是
    #: 另一个名字下的另一条路——不在这里替它换算，换算就成了这道闸自己发明的事实。
    if "fylite:b0" not in dev["machine"]:
        pytest.skip("拖回来的装置牌没有 machine.fylite:b0（上游 A-Box 不带；"
                    "内核仓那份 committed 的有，2026-09-02 随 machine_desc/ 废弃）")
    assert dev["machine"]["fylite:b0"] == pytest.approx(pre["tf"]["b0"])
